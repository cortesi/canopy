-- Write the character classes of Neovim's word motions as a Rust module.
--
-- Neovim splits words where the class of the characters changes: 0 for blanks,
-- 1 for punctuation, 2 for word characters, and other values for emoji and
-- for scripts such as CJK. This script asks Neovim for the class of every
-- code point with `charclass()`, under the default 'iskeyword', and prints
-- the ranges whose class is not 2.
--
-- Regenerate the module from the root of the repository:
--
--   nvim --headless --clean -l crates/canopy-widgets/tests/vim/char_classes.lua \
--     > crates/canopy-widgets/src/editor/vi/class.rs
--   ncode fmt crates/canopy-widgets/src/editor/vi/class.rs

local ranges = {}
local first, last, class = nil, nil, nil

local function flush()
  if first ~= nil and class ~= 2 then
    ranges[#ranges + 1] = string.format('    (0x%04x, 0x%04x, %d),', first, last, class)
  end
end

for code = 0, 0x10FFFF do
  if code < 0xD800 or code > 0xDFFF then
    local this = code == 0 and 0 or vim.fn.charclass(vim.fn.nr2char(code))
    if this == class and last == code - 1 then
      last = code
    else
      flush()
      first, last, class = code, code, this
    end
  end
end
flush()

local version = vim.version()
local out = {
  '//! Character classes of Vim\'s word motions, from Neovim.',
  '//!',
  string.format(
    '//! Generated by `tests/vim/char_classes.lua` from Neovim %d.%d.%d. Do not edit.',
    version.major,
    version.minor,
    version.patch
  ),
  '',
  'use std::cmp::Ordering;',
  '',
  '/// Return the class of `c` for word motions: 0 for blanks, 1 for',
  '/// punctuation, and 2 or more for the characters of words. Two',
  '/// characters of different classes are in different words.',
  'pub(super) fn char_class(c: char) -> u32 {',
  '    let code = u32::from(c);',
  '    match CLASSES.binary_search_by(|&(first, last, _)| {',
  '        if last < code {',
  '            Ordering::Less',
  '        } else if first > code {',
  '            Ordering::Greater',
  '        } else {',
  '            Ordering::Equal',
  '        }',
  '    }) {',
  '        Ok(index) => CLASSES[index].2,',
  '        Err(_) => 2,',
  '    }',
  '}',
  '',
  '/// Sorted ranges of code points, first and last inclusive, whose class is',
  '/// not 2.',
  'const CLASSES: &[(u32, u32, u32)] = &[',
}
for _, line in ipairs(ranges) do
  out[#out + 1] = line
end
out[#out + 1] = '];'
io.stdout:write(table.concat(out, '\n') .. '\n')
vim.cmd('qa!')
