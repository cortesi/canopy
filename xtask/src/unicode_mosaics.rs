/// Write the fixture from `data`, a copy of `UnicodeData.txt`, or with
/// `check`, fail when the fixture on disk differs from what it gives.
pub fn run(workspace_root: &Path, data: &Path, check: bool) -> bool {
    let result = fs::read_to_string(data)
        .map_err(|error| format!("cannot read {}: {error}", data.display()))
        .and_then(|source| fixture(&source))
        .and_then(|fixture| {
            let path = workspace_root.join(OUTPUT);
            if check {
                let current = fs::read_to_string(&path)
                    .map_err(|error| format!("cannot read {OUTPUT}: {error}"))?;
                if current != fixture {
                    return Err(format!(
                        "{OUTPUT} is stale: run `cargo xtask unicode-mosaics UnicodeData.txt`"
                    ));
                }
                println!("{OUTPUT} is current");
            } else {
                fs::write(&path, fixture)
                    .map_err(|error| format!("cannot write {OUTPUT}: {error}"))?;
                println!("wrote {OUTPUT}");
            }
            Ok(())
        });
    match result {
        Ok(()) => true,
        Err(error) => {
            eprintln!("{error}");
            false
        }
    }
}

/// The fixture for a `UnicodeData.txt`: its header, and one `CODE;NAME` line
/// for each character of [`RANGES`].
fn fixture(source: &str) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("# Names of the mosaic characters that canopy-mosaic draws.\n#\n");
    out.push_str(&format!("# Unicode version: {VERSION}\n"));
    out.push_str(&format!("# Source: {SOURCE}\n"));
    out.push_str("# Generated by: cargo xtask unicode-mosaics UnicodeData.txt\n#\n");
    for line in NOTICE.lines() {
        if line.is_empty() {
            out.push_str("#\n");
        } else {
            out.push_str(&format!("# {line}\n"));
        }
    }
    let mut count = 0;
    for line in source.lines() {
        let mut fields = line.split(';');
        let (Some(code), Some(name)) = (fields.next(), fields.next()) else {
            continue;
        };
        let value = u32::from_str_radix(code, 16)
            .map_err(|error| format!("bad code point {code:?}: {error}"))?;
        if RANGES
            .iter()
            .any(|(first, last)| (*first..=*last).contains(&value))
        {
            out.push_str(&format!("{code};{name}\n"));
            count += 1;
        }
    }
    let expected: u32 = RANGES.iter().map(|(first, last)| last - first + 1).sum();
    if count != expected {
        return Err(format!(
            "found {count} of {expected} characters: is this Unicode {VERSION} or later?"
        ));
    }
    Ok(out)
}
