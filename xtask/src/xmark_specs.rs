//! Generate canopy-xmark's spec tests from its spec files.
//!
//! Each example in a spec file becomes one test in `tests/suite`. An example
//! opens with a fence of 32 backticks and `example`, and a suffix such as
//! `example_wikilinks` names the extensions it enables. Its Markdown and its
//! expected HTML are separated by a line holding only `.`.

use std::{
    fs,
    path::{Path, PathBuf},
};

/// The fence that opens and closes an example.
const FENCE: &str = "````````````````````````````````";

/// Spec files outside `specs/`, relative to the crate.
const THIRD_PARTY: [&str; 5] = [
    "third_party/CommonMark/spec.txt",
    "third_party/CommonMark/smart_punct.txt",
    "third_party/GitHub/gfm_table.txt",
    "third_party/GitHub/gfm_strikethrough.txt",
    "third_party/GitHub/gfm_tasklist.txt",
];

/// Example suffixes and the extensions they enable, as the test helper names
/// them.
const SUFFIXES: [(&str, &[&str]); 14] = [
    ("", &[]),
    ("_smartpunct", &["smart_punct"]),
    ("_metadata_blocks", &["metadata_blocks"]),
    ("_old_footnotes", &["old_footnotes"]),
    ("_super_sub", &["subscript"]),
    ("_super_sub_strikethrough", &["subscript", "strikethrough"]),
    ("_wikilinks", &["wikilinks"]),
    ("_deflists", &["deflists"]),
    ("_container_extensions", &["container_extensions"]),
    ("_cjk_friendly_emphasis", &["cjk_friendly_emphasis"]),
    (
        "_cjk_friendly_emphasis_strikethrough",
        &["cjk_friendly_emphasis", "strikethrough"],
    ),
    ("_strikethrough", &["strikethrough"]),
    ("_autolinks", &["autolinks"]),
    ("_xmark", &["xmark"]),
];

/// One example: its Markdown, its expected HTML, and its extensions.
struct Example {
    /// The Markdown source.
    original: String,
    /// The HTML it renders to.
    expected: String,
    /// The extensions the example enables.
    extensions: &'static [&'static str],
}

/// Write the suites, or with `check`, fail when they differ from what the
/// specs give.
pub fn run(workspace_root: &Path, check: bool) -> bool {
    match generate(&workspace_root.join("crates/canopy-xmark"), check) {
        Ok(stale) if check && !stale.is_empty() => {
            for path in stale {
                eprintln!("stale: {}", path.display());
            }
            eprintln!("run `cargo xtask xmark-specs` to regenerate the spec tests");
            false
        }
        Ok(_) => true,
        Err(error) => {
            eprintln!("{error}");
            false
        }
    }
}

/// Generate every suite and its `mod.rs`, returning the files that changed.
fn generate(crate_dir: &Path, check: bool) -> Result<Vec<PathBuf>, String> {
    let mut specs = fs::read_dir(crate_dir.join("specs"))
        .map_err(|error| format!("reading specs: {error}"))?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "txt"))
        .chain(THIRD_PARTY.iter().map(|path| crate_dir.join(path)))
        .collect::<Vec<_>>();
    specs.sort_by(|a, b| a.file_stem().cmp(&b.file_stem()));

    let suite = crate_dir.join("tests/suite");
    let mut outputs = Vec::new();
    let mut module = String::from(HEADER);
    module.push_str("\npub use super::test_markdown_html;\n\n");
    for spec in &specs {
        let name = spec
            .file_stem()
            .and_then(|stem| stem.to_str())
            .ok_or_else(|| format!("{} has no usable name", spec.display()))?;
        let text = fs::read_to_string(spec)
            .map_err(|error| format!("reading {}: {error}", spec.display()))?;
        let examples = examples(&text).map_err(|error| format!("{}: {error}", spec.display()))?;
        outputs.push((suite.join(format!("{name}.rs")), tests(name, &examples)));
        module.push_str(&format!("mod {name};\n"));
    }
    outputs.push((suite.join("mod.rs"), module));

    let mut changed = Vec::new();
    for (path, contents) in outputs {
        if fs::read_to_string(&path).ok().as_deref() == Some(contents.as_str()) {
            continue;
        }
        if !check {
            fs::write(&path, &contents)
                .map_err(|error| format!("writing {}: {error}", path.display()))?;
        }
        changed.push(path);
    }
    Ok(changed)
}

/// The comment that opens each generated file.
const HEADER: &str =
    "// Generated by `cargo xtask xmark-specs` from the spec files. Do not edit it.\n";

/// Read the examples of one spec file.
fn examples(spec: &str) -> Result<Vec<Example>, String> {
    let opening = format!("{FENCE} example");
    let mut examples = Vec::new();
    let mut rest = spec;
    while let Some(at) = rest.find(&opening) {
        let after = &rest[at + opening.len()..];
        let line_end = after.find('\n').ok_or("an example fence never ends")?;
        let suffix = &after[..line_end];
        let extensions = SUFFIXES
            .iter()
            .find(|(known, _)| *known == suffix)
            .map(|(_, extensions)| *extensions)
            .ok_or_else(|| format!("unknown example suffix {suffix:?}"))?;
        let body = &after[line_end + 1..];
        let split = body.find("\n.\n").ok_or("an example has no `.` line")? + 1;
        let expected = &body[split + 2..];
        // The closing fence ends its line, or the file.
        let close = expected
            .match_indices(FENCE)
            .map(|(at, _)| at)
            .find(|&at| {
                (at == 0 || expected[..at].ends_with('\n'))
                    && matches!(
                        expected[at + FENCE.len()..].chars().next(),
                        None | Some('\n')
                    )
            })
            .ok_or("an example is never closed")?;
        examples.push(Example {
            original: body[..split].replace('→', "\t"),
            expected: expected[..close].replace('→', "\t"),
            extensions,
        });
        rest = expected[close + FENCE.len()..]
            .strip_prefix('\n')
            .unwrap_or_default();
    }
    Ok(examples)
}

/// The tests of one spec file.
fn tests(name: &str, examples: &[Example]) -> String {
    let mut out = String::from(HEADER);
    out.push_str("\nuse super::test_markdown_html;\n");
    for (index, example) in examples.iter().enumerate() {
        let extensions = example
            .extensions
            .iter()
            .map(|extension| format!("{extension:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            r###"
#[test]
fn {name}_test_{number}() {{
    let original = r##"{original}"##;
    let expected = r##"{expected}"##;

    test_markdown_html(original, expected, &[{extensions}]);
}}
"###,
            number = index + 1,
            original = example.original,
            expected = example.expected,
        ));
    }
    out
}
